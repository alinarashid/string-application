package com.pluralsight;

public class VariableApp {

    public static void main(String[] args) {
        // Question 1: favorite color
        String favoriteColor = "Jade";
        System.out.println("My favorite color is "+ favoriteColor);

        // Question 2: year I started this class
        int year = 2026;
        System.out.println("I joined YUU in the year "+ year);

        // Question 3: middle initial
        char middleInitial = 'A';
        System.out.println("My middle initial is "+  middleInitial);

        // Question 4: do I have pets?
        boolean hasPet = false ;
        System.out.println("Do I have pets? "+ hasPet);

        // Question 5: a nice saying
        String message = "Don't judge a book by its cover";
        System.out.println("Message: "+ message);


    }

}
